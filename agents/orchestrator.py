"""
VerityOS Orchestrator
=====================
Module: agents/orchestrator.py (Member 1)

Responsibilities:
- Coordinates the end-to-end VerityOS workflow:
  Research Agent -> Data Agent -> Verification Agent -> Trust Engine -> Policy Gate -> Final Response
- Passes strongly typed, validated envelopes across agent hand-offs.
- Assembles VerificationPacket for Member 2's Trust Engine.
- Supports both:
  1. Explicit mock mode via evaluate_trust_engine_mock()
  2. Production mode via Member 2's evaluate_trust_engine() (when installed)
- Rule: Never silently substitutes mock Trust Engine when production is requested.
- Applies canonical policy decision mapping:
  PASS   -> APPROVED
  REVIEW -> QUARANTINED
  REJECT -> REJECTED
  EMPTY  -> INSUFFICIENT_DATA
  ERROR  -> ERROR
- Strictly enforces fail-safe rules:
  * Contradicted claims can NEVER produce APPROVED.
  * Tampered evidence can NEVER produce APPROVED.
  * Missing/malformed Trust Engine responses can NEVER produce APPROVED.
  * Empty research safely halts pipeline with INSUFFICIENT_DATA.
- Preserves task_id, claim_id, and evidence_id immutably across all stages.
- Generates an auditable chronological trace in audit_trail.
- Returns FinalPipelineResponse with user-safe error handling (no raw tracebacks).
"""

from datetime import datetime, timezone
import logging
from typing import Any, Optional, Union
from pydantic import ValidationError

from agents.data_agent import run_data_agent
from agents.mocks import verify_evidence_integrity
from agents.research_agent import run_research_agent
from agents.trust_engine_mock import evaluate_trust_engine_mock
from agents.verification_agent import run_verification_agent
from shared.schemas import (
    AuditStep,
    ClaimRecord,
    EvidenceRecord,
    ExecutionMode,
    FinalPipelineResponse,
    ModuleStatus,
    ProductState,
    TrustAssessmentRecord,
    TrustDecision,
    TrustEngineOutput,
    VerificationPacket,
    VerificationPacketData,
    VerificationResultRecord,
    VerificationStatus,
)

logger = logging.getLogger("verityos.agents.orchestrator")


def _now_iso() -> str:
    """Returns current UTC timestamp in ISO 8601 format."""
    return datetime.now(timezone.utc).isoformat()


def execute_pipeline(
    task_id: str,
    query: str,
    mode: ExecutionMode = ExecutionMode.MOCK,
    mock_scenario: Optional[str] = "supported",
    use_mock_trust_engine: bool = True,
) -> FinalPipelineResponse:
    """
    Main orchestration entry point for VerityOS.
    Called by Member 3's backend API (/api/analyze).

    Args:
        task_id: Unique task identifier generated by caller.
        query: User input query or goal.
        mode: ExecutionMode.MOCK or ExecutionMode.LIVE.
        mock_scenario: One of 'supported', 'contradicted', 'empty', 'tampered' (when mode == MOCK).
        use_mock_trust_engine: If True, uses Member 1's mock test double.
                               If False, calls Member 2's production Trust Engine.

    Returns:
        FinalPipelineResponse conforming to the agreed shared contract.
    """
    audit_trail: list[AuditStep] = []
    warnings: list[str] = []

    def record_audit(stage: str, agent: str, status: ModuleStatus, summary: str, details: Optional[dict[str, Any]] = None):
        audit_trail.append(
            AuditStep(
                stage=stage,
                agent=agent,
                status=status,
                timestamp=_now_iso(),
                summary=summary,
                details=details,
            )
        )

    # 1. Validate Input Parameters
    if not task_id or not isinstance(task_id, str) or not task_id.strip():
        logger.error("execute_pipeline called with invalid task_id.")
        return FinalPipelineResponse(
            task_id="unknown_task",
            query=query or "",
            mode=mode,
            product_state=ProductState.ERROR,
            summary="Pipeline failed: invalid task_id provided.",
            error="Invalid task_id: must be a non-empty string.",
            audit_trail=[],
        )

    task_id = task_id.strip()

    if not query or not isinstance(query, str) or not query.strip():
        logger.info("Task %s: Pipeline received empty query.", task_id)
        record_audit("intake", "orchestrator", ModuleStatus.EMPTY, "User query was empty.")
        return FinalPipelineResponse(
            task_id=task_id,
            query="",
            mode=mode,
            product_state=ProductState.INSUFFICIENT_DATA,
            summary="No query provided. Analysis could not be performed.",
            audit_trail=audit_trail,
            warnings=["EMPTY_QUERY"],
        )

    query = query.strip()
    record_audit("intake", "orchestrator", ModuleStatus.SUCCESS, f"Initiated task for query: '{query[:80]}...'")

    # 2. Stage 1: Research Agent
    research_envelope = run_research_agent(
        task_id=task_id,
        query=query,
        mode=mode,
        mock_scenario=mock_scenario,
    )
    record_audit(
        stage="research",
        agent=research_envelope.agent,
        status=research_envelope.status,
        summary=f"Research stage completed with status: {research_envelope.status.value}",
        details={"mock_scenario": mock_scenario} if mode == ExecutionMode.MOCK else None,
    )

    if research_envelope.status == ModuleStatus.ERROR:
        return FinalPipelineResponse(
            task_id=task_id,
            query=query,
            mode=mode,
            product_state=ProductState.ERROR,
            summary="Pipeline aborted: research stage encountered an error.",
            error=research_envelope.error or "Research stage failed.",
            audit_trail=audit_trail,
        )

    raw_evidence = research_envelope.data.get("evidence", [])
    if research_envelope.status == ModuleStatus.EMPTY or not raw_evidence:
        record_audit("policy_gate", "orchestrator", ModuleStatus.SUCCESS, "Pipeline halted: zero evidence collected.")
        return FinalPipelineResponse(
            task_id=task_id,
            query=query,
            mode=mode,
            product_state=ProductState.INSUFFICIENT_DATA,
            summary="Research yielded zero evidence records. Analysis could not be completed.",
            audit_trail=audit_trail,
            warnings=["INSUFFICIENT_DATA: No sources found for query."],
        )

    try:
        evidence_list = [EvidenceRecord.model_validate(e) for e in raw_evidence]
    except Exception as exc:
        logger.exception("Task %s: Schema validation error on collected evidence: %s", task_id, exc)
        return FinalPipelineResponse(
            task_id=task_id,
            query=query,
            mode=mode,
            product_state=ProductState.ERROR,
            summary="Pipeline aborted: malformed evidence records.",
            error="Collected evidence failed schema validation.",
            audit_trail=audit_trail,
        )

    # 3. Stage 2: Data Agent
    data_envelope = run_data_agent(
        task_id=task_id,
        evidence=evidence_list,
        query=query,
        mode=mode,
    )
    record_audit(
        stage="data_extraction",
        agent=data_envelope.agent,
        status=data_envelope.status,
        summary=f"Data extraction completed with status: {data_envelope.status.value}",
    )

    if data_envelope.status == ModuleStatus.ERROR:
        return FinalPipelineResponse(
            task_id=task_id,
            query=query,
            mode=mode,
            product_state=ProductState.ERROR,
            summary="Pipeline aborted: data extraction stage encountered an error.",
            error=data_envelope.error or "Data extraction stage failed.",
            evidence=evidence_list,
            audit_trail=audit_trail,
        )

    raw_claims = data_envelope.data.get("claims", [])
    if data_envelope.status == ModuleStatus.EMPTY or not raw_claims:
        record_audit("policy_gate", "orchestrator", ModuleStatus.SUCCESS, "Pipeline halted: no claims extracted.")
        return FinalPipelineResponse(
            task_id=task_id,
            query=query,
            mode=mode,
            product_state=ProductState.INSUFFICIENT_DATA,
            summary="No atomic claims could be extracted from evidence.",
            evidence=evidence_list,
            audit_trail=audit_trail,
            warnings=["NO_ATOMIC_CLAIMS_EXTRACTED"],
        )

    try:
        claims_list = [ClaimRecord.model_validate(c) for c in raw_claims]
    except Exception as exc:
        logger.exception("Task %s: Schema validation error on extracted claims: %s", task_id, exc)
        return FinalPipelineResponse(
            task_id=task_id,
            query=query,
            mode=mode,
            product_state=ProductState.ERROR,
            summary="Pipeline aborted: malformed claim records.",
            error="Extracted claims failed schema validation.",
            evidence=evidence_list,
            audit_trail=audit_trail,
        )

    # 4. Stage 3: Verification Agent
    ver_envelope = run_verification_agent(
        task_id=task_id,
        claims=claims_list,
        evidence=evidence_list,
        mode=mode,
    )
    record_audit(
        stage="verification",
        agent=ver_envelope.agent,
        status=ver_envelope.status,
        summary=f"Verification completed with status: {ver_envelope.status.value}",
    )

    if ver_envelope.status == ModuleStatus.ERROR:
        return FinalPipelineResponse(
            task_id=task_id,
            query=query,
            mode=mode,
            product_state=ProductState.ERROR,
            summary="Pipeline aborted: verification stage encountered an error.",
            error=ver_envelope.error or "Verification stage failed.",
            evidence=evidence_list,
            claims=claims_list,
            audit_trail=audit_trail,
        )

    raw_results = ver_envelope.data.get("verification_results", [])
    try:
        ver_results = [VerificationResultRecord.model_validate(vr) for vr in raw_results]
    except Exception as exc:
        logger.exception("Task %s: Schema validation error on verification results: %s", task_id, exc)
        return FinalPipelineResponse(
            task_id=task_id,
            query=query,
            mode=mode,
            product_state=ProductState.ERROR,
            summary="Pipeline aborted: malformed verification results.",
            error="Verification results failed schema validation.",
            evidence=evidence_list,
            claims=claims_list,
            audit_trail=audit_trail,
        )

    # 5. Stage 4: Trust Engine Assembly & Evaluation
    verification_packet = VerificationPacket(
        task_id=task_id,
        status=ModuleStatus.SUCCESS,
        agent="verification_agent",
        mode=mode,
        data=VerificationPacketData(
            claims=claims_list,
            evidence=evidence_list,
            verification_results=ver_results,
        ),
    )

    trust_output: Optional[TrustEngineOutput] = None

    if use_mock_trust_engine:
        # Explicit mock Trust Engine call
        try:
            trust_output = evaluate_trust_engine_mock(verification_packet)
            record_audit(
                stage="trust_engine",
                agent="trust_engine_mock",
                status=trust_output.status,
                summary="Executed Member 1 mock Trust Engine evaluation.",
            )
        except Exception as exc:
            logger.exception("Task %s: Exception raised during mock Trust Engine execution: %s", task_id, exc)
            record_audit(
                stage="trust_engine",
                agent="trust_engine_mock",
                status=ModuleStatus.ERROR,
                summary="Mock Trust Engine encountered an unhandled exception.",
            )
            return FinalPipelineResponse(
                task_id=task_id,
                query=query,
                mode=mode,
                product_state=ProductState.QUARANTINED,
                summary="Trust evaluation encountered an internal error. Quarantined for review.",
                error="Trust Engine execution error. Please inspect system logs.",
                evidence=evidence_list,
                claims=claims_list,
                verification_results=ver_results,
                audit_trail=audit_trail,
                warnings=["TRUST_ENGINE_EXCEPTION: Analysis quarantined due to evaluation failure."],
            )
    else:
        # Production integration with Member 2's Trust Engine
        # Rule 5: Never silently substitute the mock Trust Engine for production
        try:
            from trust_engine.trust_engine import evaluate_trust_engine
            logger.info("Task %s: Calling Member 2 production evaluate_trust_engine().", task_id)
            raw_trust_res = evaluate_trust_engine(verification_packet)
            if isinstance(raw_trust_res, TrustEngineOutput):
                trust_output = raw_trust_res
            elif isinstance(raw_trust_res, dict):
                trust_output = TrustEngineOutput.model_validate(raw_trust_res)
            else:
                raise TypeError(f"Unexpected return type from evaluate_trust_engine: {type(raw_trust_res)}")
            record_audit(
                stage="trust_engine",
                agent="trust_engine_production",
                status=trust_output.status,
                summary="Executed Member 2 production Trust Engine.",
            )
        except ImportError:
            logger.error("Task %s: Member 2 production Trust Engine is not installed.", task_id)
            record_audit(
                stage="trust_engine",
                agent="orchestrator",
                status=ModuleStatus.ERROR,
                summary="Production Trust Engine requested but module 'trust_engine.trust_engine' is not available.",
            )
            return FinalPipelineResponse(
                task_id=task_id,
                query=query,
                mode=mode,
                product_state=ProductState.ERROR,
                summary="Production Trust Engine is not installed or available.",
                error=(
                    "Production Trust Engine (Member 2) is not available. "
                    "Set use_mock_trust_engine=True to run with the test double."
                ),
                evidence=evidence_list,
                claims=claims_list,
                verification_results=ver_results,
                audit_trail=audit_trail,
            )
        except Exception as exc:
            logger.exception("Task %s: Exception raised during production Trust Engine execution: %s", task_id, exc)
            record_audit(
                stage="trust_engine",
                agent="trust_engine_production",
                status=ModuleStatus.ERROR,
                summary="Production Trust Engine encountered an unhandled exception.",
            )
            # Fail-safe rule: Trust Engine failure can NEVER result in APPROVED. Maps to QUARANTINED.
            return FinalPipelineResponse(
                task_id=task_id,
                query=query,
                mode=mode,
                product_state=ProductState.QUARANTINED,
                summary="Trust evaluation encountered an internal error. Quarantined for review.",
                error="Trust Engine execution error. Please inspect system logs.",
                evidence=evidence_list,
                claims=claims_list,
                verification_results=ver_results,
                audit_trail=audit_trail,
                warnings=["TRUST_ENGINE_EXCEPTION: Analysis quarantined due to evaluation failure."],
            )

    # 6. Validate Trust Engine Output (Fail-Safe Checks)
    if (
        not trust_output
        or trust_output.status == ModuleStatus.ERROR
        or not trust_output.trust_assessment
    ):
        logger.warning("Task %s: Trust Engine returned invalid or error output.", task_id)
        record_audit("policy_gate", "orchestrator", ModuleStatus.ERROR, "Trust Engine output was invalid or missing.")
        # Fail-safe rule: Invalid output maps to QUARANTINED
        return FinalPipelineResponse(
            task_id=task_id,
            query=query,
            mode=mode,
            product_state=ProductState.QUARANTINED,
            summary="Trust Engine assessment was invalid or incomplete. Quarantined for review.",
            error=trust_output.error if trust_output else "Missing trust assessment output.",
            evidence=evidence_list,
            claims=claims_list,
            verification_results=ver_results,
            audit_trail=audit_trail,
            warnings=["MALFORMED_TRUST_OUTPUT: Quarantined for human inspection."],
        )

    assessment: TrustAssessmentRecord = trust_output.trust_assessment
    trust_decision: TrustDecision = assessment.decision
    overall_score: float = assessment.overall_score
    warnings.extend(assessment.warnings)

    # 7. Stage 5: Orchestrator Policy Gate & Fail-Safe Invariants
    # Apply baseline mapping
    if trust_decision == TrustDecision.PASS:
        mapped_state = ProductState.APPROVED
    elif trust_decision == TrustDecision.REVIEW:
        mapped_state = ProductState.QUARANTINED
    elif trust_decision == TrustDecision.REJECT:
        mapped_state = ProductState.REJECTED
    else:
        mapped_state = ProductState.QUARANTINED

    # Strict Fail-Safe Invariant Checks:
    # Rule 7A: Contradicted claims must NEVER result in APPROVED
    has_contradictions = any(
        vr.status == VerificationStatus.CONTRADICTED or len(vr.contradicting_evidence_ids) > 0
        for vr in ver_results
    )
    if has_contradictions and mapped_state == ProductState.APPROVED:
        logger.warning("Task %s: Policy gate override: Contradicted claim cannot be APPROVED.", task_id)
        mapped_state = ProductState.QUARANTINED
        warnings.append("POLICY_GATE_OVERRIDE: Contradicted claim detected; overridden from APPROVED to QUARANTINED.")

    # Rule 7B: Tampered evidence must NEVER result in APPROVED
    has_tamper = any(not verify_evidence_integrity(ev) for ev in evidence_list)
    if has_tamper and mapped_state in [ProductState.APPROVED, ProductState.QUARANTINED]:
        logger.warning("Task %s: Policy gate override: Tampered evidence cannot be APPROVED/QUARANTINED.", task_id)
        mapped_state = ProductState.REJECTED
        warnings.append("POLICY_GATE_OVERRIDE: Cryptographic integrity failure detected; overridden to REJECTED.")

    record_audit(
        stage="policy_gate",
        agent="orchestrator",
        status=ModuleStatus.SUCCESS,
        summary=f"Policy gate mapped decision '{trust_decision.value}' to product state '{mapped_state.value}'.",
        details={"mapped_state": mapped_state.value, "overall_trust_score": overall_score},
    )

    # 8. Assemble Explanatory Final Summary
    prefix = "[DEMO / MOCK RUN] " if mode == ExecutionMode.MOCK else ""
    if mapped_state == ProductState.APPROVED:
        summary_text = (
            f"{prefix}Verified successfully: All {len(claims_list)} claim(s) directly corroborated "
            f"by {len(evidence_list)} independent, authoritative source(s) with verified cryptographic integrity. "
            f"Overall trust score: {overall_score:.1f}/100."
        )
    elif mapped_state == ProductState.QUARANTINED:
        summary_text = (
            f"{prefix}Quarantined for Review: Discrepancies or conflicting evidence detected across sources. "
            f"Human review required before downstream acceptance. Overall trust score: {overall_score:.1f}/100."
        )
    elif mapped_state == ProductState.REJECTED:
        summary_text = (
            f"{prefix}Rejected: Severe integrity or policy failure detected. One or more source documents "
            f"failed SHA-256 cryptographic fingerprint validation. Overall trust score: {overall_score:.1f}/100."
        )
    else:
        summary_text = f"{prefix}Status: {mapped_state.value}. Overall trust score: {overall_score:.1f}/100."

    return FinalPipelineResponse(
        task_id=task_id,
        query=query,
        mode=mode,
        product_state=mapped_state,
        trust_decision=trust_decision,
        overall_trust_score=overall_score,
        summary=summary_text,
        claims=claims_list,
        evidence=evidence_list,
        verification_results=ver_results,
        trust_assessment=assessment,
        audit_trail=audit_trail,
        warnings=warnings,
        error=None,
    )

"""
VerityOS Trust Engine Mock & Fallback Test Double
=================================================
Module: agents/trust_engine_mock.py (Member 1)

DISCLAIMER:
This module is a deterministic test double / fallback mock used exclusively
by Member 1 (AI Agents & Orchestration) and Member 3 (Backend API) for local
testing prior to Member 2's live Trust Engine delivery.
It does NOT implement Member 2's proprietary trust scoring weights or production
algorithms and is explicitly marked as MOCK in all evaluation outputs.

Supported Decisions:
- PASS: All claims corroborated, hashes valid, zero contradictions.
- REVIEW: Unresolved contradictions or insufficient evidence coverage.
- REJECT: Cryptographic integrity violation (tampered hash) or severe conflict.
"""

from datetime import datetime, timezone
import logging
from typing import Any, Optional, Union
from pydantic import ValidationError

from agents.mocks import compute_sha256, verify_evidence_integrity
from shared.schemas import (
    ModuleStatus,
    TrustAssessmentRecord,
    TrustDecision,
    TrustDimensionScores,
    TrustEngineOutput,
    VerificationPacket,
    VerificationStatus,
)

logger = logging.getLogger("verityos.agents.trust_engine_mock")

MOCK_DISCLAIMER_WARNING = (
    "[MOCK TEST HARNESS] Evaluation generated by Member 1 mock double. "
    "Not verified by Member 2's production Trust Engine."
)


def evaluate_trust_engine_mock(
    verification_packet: Union[dict[str, Any], VerificationPacket]
) -> TrustEngineOutput:
    """
    Evaluates a verification packet against deterministic mock scoring rules.

    Guarantees:
    - Never returns PASS when evidence integrity check fails.
    - Never returns PASS when any claim is CONTRADICTED.
    - Returns ModuleStatus.ERROR on invalid or malformed packet schemas.
    - Explicitly stamps all outputs with the mock disclaimer.
    """
    # 1. Parse and validate input packet
    if isinstance(verification_packet, dict):
        try:
            packet = VerificationPacket.model_validate(verification_packet)
        except ValidationError as val_err:
            logger.warning("Invalid verification packet provided to mock Trust Engine: %s", val_err)
            task_id = str(verification_packet.get("task_id", "unknown_task"))
            return TrustEngineOutput(
                task_id=task_id,
                status=ModuleStatus.ERROR,
                trust_assessment=None,
                error="Invalid verification packet schema: failed validation.",
            )
        except Exception as exc:
            logger.error("Unexpected error parsing verification packet: %s", exc)
            return TrustEngineOutput(
                task_id="unknown_task",
                status=ModuleStatus.ERROR,
                trust_assessment=None,
                error="Failed to process verification packet.",
            )
    elif isinstance(verification_packet, VerificationPacket):
        packet = verification_packet
    else:
        logger.warning("Unrecognized packet type: %s", type(verification_packet))
        return TrustEngineOutput(
            task_id="unknown_task",
            status=ModuleStatus.ERROR,
            trust_assessment=None,
            error="Input must be a VerificationPacket or valid dictionary.",
        )

    task_id = packet.task_id
    evidence_list = packet.data.evidence
    claims_list = packet.data.claims
    results_list = packet.data.verification_results
    evaluated_at = datetime.now(timezone.utc).isoformat()

    # 2. Check Cryptographic Integrity (Tamper Detection)
    tampered_evidence_ids = []
    for ev in evidence_list:
        if ev.content_hash:
            if not verify_evidence_integrity(ev):
                tampered_evidence_ids.append(ev.evidence_id)

    if tampered_evidence_ids:
        reasons = [
            f"Cryptographic integrity check failed: SHA-256 fingerprint mismatch detected in evidence: {', '.join(tampered_evidence_ids)}."
        ]
        warnings = [
            MOCK_DISCLAIMER_WARNING,
            f"EVIDENCE_INTEGRITY_VIOLATION: Evidence {tampered_evidence_ids} modified post-ingestion.",
        ]
        dimension_scores = TrustDimensionScores(
            source_quality=20.0,
            evidence_support=10.0,
            freshness=50.0,
            corroboration=0.0,
            consistency=0.0,
            data_quality=0.0,  # Zeroed out due to integrity check failure
        )
        return TrustEngineOutput(
            task_id=task_id,
            status=ModuleStatus.SUCCESS,
            trust_assessment=TrustAssessmentRecord(
                overall_score=13.3,
                decision=TrustDecision.REJECT,  # Strictly REJECT on tamper
                dimension_scores=dimension_scores,
                reasons=reasons,
                warnings=warnings,
                evaluated_at=evaluated_at,
            ),
        )

    # 3. Check for Empty Evidence or Claims
    if not evidence_list or not claims_list:
        return TrustEngineOutput(
            task_id=task_id,
            status=ModuleStatus.SUCCESS,
            trust_assessment=TrustAssessmentRecord(
                overall_score=0.0,
                decision=TrustDecision.REVIEW,
                dimension_scores=TrustDimensionScores(
                    source_quality=0.0,
                    evidence_support=0.0,
                    freshness=0.0,
                    corroboration=0.0,
                    consistency=0.0,
                    data_quality=0.0,
                ),
                reasons=["No verifiable claims or evidence records present in packet."],
                warnings=[MOCK_DISCLAIMER_WARNING, "EMPTY_DATASET"],
                evaluated_at=evaluated_at,
            ),
        )

    # 4. Check for Contradictions
    has_contradictions = any(
        res.status == VerificationStatus.CONTRADICTED or len(res.contradicting_evidence_ids) > 0
        for res in results_list
    )

    if has_contradictions:
        conflicting_claims = [
            res.claim_id for res in results_list if res.status == VerificationStatus.CONTRADICTED
        ]
        reasons = [
            f"Conflicting evidence detected across sources for claim(s): {', '.join(conflicting_claims)}."
        ]
        warnings = [
            MOCK_DISCLAIMER_WARNING,
            "CONTRADICTION_FLAGGED: Cross-source numerical or factual mismatch identified.",
        ]
        dimension_scores = TrustDimensionScores(
            source_quality=65.0,
            evidence_support=50.0,
            freshness=70.0,
            corroboration=25.0,
            consistency=20.0,  # Heavily penalized
            data_quality=80.0,
        )
        return TrustEngineOutput(
            task_id=task_id,
            status=ModuleStatus.SUCCESS,
            trust_assessment=TrustAssessmentRecord(
                overall_score=51.6,
                decision=TrustDecision.REVIEW,  # Strictly REVIEW (never PASS) on contradiction
                dimension_scores=dimension_scores,
                reasons=reasons,
                warnings=warnings,
                evaluated_at=evaluated_at,
            ),
        )

    # 5. Check for Insufficient Evidence
    all_insufficient = all(
        res.status == VerificationStatus.INSUFFICIENT for res in results_list
    )
    if all_insufficient:
        return TrustEngineOutput(
            task_id=task_id,
            status=ModuleStatus.SUCCESS,
            trust_assessment=TrustAssessmentRecord(
                overall_score=35.0,
                decision=TrustDecision.REVIEW,
                dimension_scores=TrustDimensionScores(
                    source_quality=40.0,
                    evidence_support=20.0,
                    freshness=60.0,
                    corroboration=10.0,
                    consistency=60.0,
                    data_quality=60.0,
                ),
                reasons=["Available evidence is insufficient to substantiate claims."],
                warnings=[MOCK_DISCLAIMER_WARNING, "INSUFFICIENT_EVIDENCE_COVERAGE"],
                evaluated_at=evaluated_at,
            ),
        )

    # 6. Supported Case (All Claims Verified and Corroborated)
    reasons = [
        "All claims directly corroborated by independent authoritative sources with verified cryptographic hashes."
    ]
    warnings = [MOCK_DISCLAIMER_WARNING]
    dimension_scores = TrustDimensionScores(
        source_quality=92.0,
        evidence_support=95.0,
        freshness=88.0,
        corroboration=90.0,
        consistency=100.0,
        data_quality=98.0,
    )
    # Simple unweighted average for mock demonstration
    mock_overall = round(
        (92.0 + 95.0 + 88.0 + 90.0 + 100.0 + 98.0) / 6.0, 1
    )

    return TrustEngineOutput(
        task_id=task_id,
        status=ModuleStatus.SUCCESS,
        trust_assessment=TrustAssessmentRecord(
            overall_score=mock_overall,
            decision=TrustDecision.PASS,
            dimension_scores=dimension_scores,
            reasons=reasons,
            warnings=warnings,
            evaluated_at=evaluated_at,
        ),
    )
